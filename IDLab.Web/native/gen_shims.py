#!/usr/bin/env python3
"""
Generates the struct-return bridge for raylib on .NET 8 WebAssembly.

The .NET 8 wasm P/Invoke table declares a native function that returns a struct by value as `int f(...)` and reads
the returned int as the ADDRESS of the struct. Real raylib functions return structs through a hidden pointer instead,
so calling them directly traps ("function signature mismatch"). Raylib-cs also binds C `bool` results as a one-byte
struct (CBool), so bool-returning functions need the same treatment. We compile raylib with every such function renamed to
rl_<name> (rename.h, force-included) and export <name> from shims.c: it calls rl_<name>, keeps the result in a static
buffer and returns its address. Struct *arguments* already match (both sides pass them by address).

usage: gen_shims.py <raylib/src> <out-dir>
"""
import re, sys, os

src, out = sys.argv[1], sys.argv[2]
headers = ['raylib.h', 'raymath.h', 'rlgl.h']
text = {h: open(os.path.join(src, h), encoding='utf-8').read() for h in headers}

structs = set()
for t in text.values():
    structs.update(re.findall(r'typedef\s+struct\s+\w*\s*\{[^}]*\}\s*(\w+)\s*;', t, re.S))
    for a, b in re.findall(r'typedef\s+(\w+)\s+(\w+)\s*;', t):
        if a in structs: structs.add(b)
# A second pass picks up aliases of aliases (Camera → Camera3D, Texture2D → Texture ...).
for t in text.values():
    for a, b in re.findall(r'typedef\s+(\w+)\s+(\w+)\s*;', t):
        if a in structs: structs.add(b)

proto = re.compile(r'^\s*(?:RLAPI|RMAPI)\s+(?:const\s+)?(\w+)\s+(\w+)\s*\(([^)]*)\)', re.M)
funcs = {}
for h, t in text.items():
    for ret, name, params in proto.findall(t):
        if (ret in structs or ret == 'bool') and name not in funcs:
            funcs[name] = (ret, ' '.join(params.split()), h)

with open(os.path.join(out, 'rename.h'), 'w') as f:
    f.write('// GENERATED by gen_shims.py: raylib functions that return a struct are renamed rl_<name>.\n#pragma once\n')
    for n in sorted(funcs): f.write(f'#define {n} rl_{n}\n')

def arg_names(params):
    if params.strip() in ('', 'void'): return ''
    names = []
    for p in params.split(','):
        p = p.strip()
        if p == '...': raise SystemExit('variadic')
        names.append(re.findall(r'(\w+)\s*(?:\[\s*\w*\s*\])?$', p)[0])
    return ', '.join(names)

with open(os.path.join(out, 'shims.c'), 'w') as f:
    f.write('// GENERATED by gen_shims.py: exports the struct-returning raylib API the way .NET 8 wasm calls it.\n')
    f.write('#include "rename.h"\n#include <stdint.h>\n#include <stdbool.h>\n#include "raylib.h"\n#define RAYMATH_STATIC_INLINE\n#include "raymath.h"\n#include "rlgl.h"\n\n')
    for n in sorted(funcs): f.write(f'#undef {n}\n')
    f.write('\n')
    for n in sorted(funcs):
        ret, params, h = funcs[n]
        f.write(f'int {n}({params or "void"}) {{ static {ret} rl_result_; rl_result_ = rl_{n}({arg_names(params)}); return (int)(intptr_t)&rl_result_; }}\n')
print(len(funcs), 'struct-returning functions bridged')
